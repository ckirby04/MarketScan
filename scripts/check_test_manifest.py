#!/usr/bin/env python3
"""Every registered test, by name, against a committed manifest.

WHY THIS EXISTS

`docs/PROTECTED.md` lists things that look like cruft and are load-bearing, and
several of them are individual tests: a case that fails on purpose, an assertion
that cannot fire, a ban on `importlib` that stands between this project's central
architectural claim and its becoming tautological. Deleting any of them leaves the
build green and the repository measuring less, which is the failure
`docs/AUDIT.md` calls the vacuous-pass law.

Before this, each such test was protected by someone reading PROTECTED.md. That is
attention, and attention does not run in CI.

A manifest of names makes removing any test an explicit act: the test disappears,
this fails, and the only way forward is to delete the line too -- in a diff a
reviewer sees. It protects every guard that exists now and every guard added later,
without anyone having to remember to write bespoke protection for each one.

WHY NAMES RATHER THAN A COUNT

`scripts/check_skips.py` already carries a count floor, and a count cannot tell
"we deleted the importlib ban and added two cases about parsing" from "nothing
happened". Names can. The count and the manifest answer different questions and
neither replaces the other:

    the --min-tests floor    did the suite run at all?
    this manifest            is the suite still made of the same things?

WHY THE MATCH IS EXACT IN BOTH DIRECTIONS

An unlisted new test also fails, which is deliberate. It costs one `--write` per
commit that adds a test, and it buys the property that matters: a guard added today
is protected tomorrow without anyone deciding to protect it. A manifest that only
caught removals would slowly cover less of the suite while continuing to report
success -- the shape this file exists to prevent.

    python scripts/check_test_manifest.py --source ctest  --test-dir out/build/ci
    python scripts/check_test_manifest.py --source pytest
    ... --write to regenerate either.

Two manifests, because the two suites are listed by different tools and no CI job
can run both. See MANIFESTS below.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# Two suites, two manifests.
#
# The C++ suite is listed by ctest and needs a build tree; the Python suite is
# listed by pytest and needs the research dependencies. No CI job has both, and a
# single manifest split into sections would mean each job checking half a file and
# neither checking the whole -- which is how a manifest ends up half-enforced while
# reporting success.
#
# Separating them also matters for what is being protected. The guard standing
# between this project's central architectural claim and its becoming tautological
# is `no guarded module imports dynamically`, and that is a *pytest* test. A
# manifest covering only ctest would have protected everything except the thing
# most worth protecting.
MANIFESTS = {
    "ctest": REPO / "tests" / "test_manifest.txt",
    "pytest": REPO / "research" / "tests" / "test_manifest.txt",
}

# "  Test #123: the name of the test"
LISTED = re.compile(r"^\s*Test\s*#\d+:\s*(?P<name>.+?)\s*$")

# ctest prints this when it listed nothing. A comparison of two empty sets is not
# a pass, so the count is asserted rather than assumed.
TOTAL = re.compile(r"^Total Tests:\s*(?P<total>\d+)\s*$")

# "research/tests/test_x.py::test_name" or "...::test_name[param]"
#
# Everything after `.py::` to the end of the line, because a parametrised id can
# contain spaces -- `test_every_shape_of_ctest_summary_line_yields_its_total[100%
# tests passed out of 483-483]` is a real one in this suite. The first draft
# required non-space and silently named 241 of 246 tests; the total check below is
# what caught it, which is the only reason this comment exists rather than a
# manifest that was quietly five short.
COLLECTED = re.compile(r"^(?P<id>[\w./\\-]+\.py::.+)$")

# "246 tests collected in 0.87s"
PYTEST_TOTAL = re.compile(r"^(?P<total>\d+)\s+tests?\s+collected\b")

HEADER = """\
# Every test this repository registers, by name.
#
# Generated by scripts/check_test_manifest.py --write. Do not hand-edit except to
# delete a line for a test you are deliberately removing.
#
# WHY THIS FILE IS COMMITTED
#
# So that deleting a test is a visible act rather than a silent one. Several tests
# in this suite are load-bearing in a way their names do not advertise -- see
# docs/PROTECTED.md -- and removing one leaves the build green while the repository
# measures less. If a name vanishes from ctest and not from here, CI fails and says
# which.
#
# Adding a test also fails until you regenerate, on purpose: that is what makes a
# guard written today protected tomorrow without anyone remembering to protect it.
"""


def list_tests(test_dir: str | None, preset: str | None) -> tuple[list[str], int | None]:
    """Every registered test name, and the total ctest reported."""
    command = ["ctest", "-N"]
    if preset:
        command += ["--preset", preset]
    if test_dir:
        command += ["--test-dir", test_dir]

    completed = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    if completed.returncode != 0:
        print(completed.stdout + completed.stderr, file=sys.stderr)
        raise SystemExit(f"ctest -N exited {completed.returncode}")

    names: list[str] = []
    total: int | None = None
    for line in (completed.stdout + completed.stderr).splitlines():
        listed = LISTED.match(line)
        if listed:
            names.append(listed.group("name"))
            continue
        counted = TOTAL.match(line.strip())
        if counted:
            total = int(counted.group("total"))
    return names, total


def list_pytest(target: str) -> tuple[list[str], int | None]:
    """Every collected pytest node id, and the total pytest reported.

    Node ids rather than bare function names, because parametrised cases share a
    name and differ only in their id -- and the parametrised ones here include the
    guard that fails when a guarded module reaches the bindings.
    """
    command = [sys.executable, "-m", "pytest", target, "--collect-only", "-q", "-p", "no:randomly"]
    completed = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    if completed.returncode != 0:
        print(completed.stdout + completed.stderr, file=sys.stderr)
        raise SystemExit(f"pytest --collect-only exited {completed.returncode}")

    names: list[str] = []
    total: int | None = None
    for line in completed.stdout.splitlines():
        stripped = line.strip()
        collected = COLLECTED.match(stripped)
        if collected:
            names.append(collected.group("id").replace("\\", "/"))
            continue
        counted = PYTEST_TOTAL.match(stripped)
        if counted:
            total = int(counted.group("total"))
    return names, total


def load_manifest(path: Path) -> list[str]:
    if not path.is_file():
        return []
    out = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out


def write_manifest(path: Path, names: list[str]) -> None:
    body = "\n".join(sorted(names))
    path.write_text(HEADER + "\n" + body + "\n", encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        choices=sorted(MANIFESTS),
        default="ctest",
        help="which suite to check (default: %(default)s)",
    )
    parser.add_argument("--test-dir", help="build directory to list tests from (ctest)")
    parser.add_argument("--preset", help="ctest preset to list tests from (ctest)")
    parser.add_argument(
        "--target", default="research/tests", help="what to collect (pytest; default: %(default)s)"
    )
    parser.add_argument("--manifest", type=Path, default=None)
    parser.add_argument(
        "--write",
        action="store_true",
        help="regenerate the manifest from what the suite currently registers",
    )
    args = parser.parse_args(argv)

    if args.manifest is None:
        args.manifest = MANIFESTS[args.source]

    if args.source == "ctest":
        names, total = list_tests(args.test_dir, args.preset)
        lister = "ctest -N"
    else:
        names, total = list_pytest(args.target)
        lister = "pytest --collect-only"

    # A listing of nothing must not compare equal to anything. ctest exits
    # non-zero when it finds no tests, which is checked above, and the total is
    # checked here because the two failures have different causes.
    if total is None:
        print(f"{lister} did not report a total; refusing to compare against the manifest.",
              file=sys.stderr)
        return 1
    if total != len(names):
        print(f"{lister} reported {total} tests and named {len(names)}; the listing was not "
              "parsed completely, so the comparison would be against the wrong set.",
              file=sys.stderr)
        return 1
    if not names:
        print(f"{lister} registered no tests; there is nothing to check the manifest against.",
              file=sys.stderr)
        return 1

    if args.write:
        write_manifest(args.manifest, names)
        print(f"wrote {len(names)} test names to {args.manifest.relative_to(REPO)}")
        return 0

    recorded = load_manifest(args.manifest)
    if not recorded:
        print(f"{args.manifest.relative_to(REPO)} is missing or empty. Generate it with "
              "--write, and commit it.", file=sys.stderr)
        return 1

    live = set(names)
    listed = set(recorded)

    gone = sorted(listed - live)
    added = sorted(live - listed)

    if not gone and not added:
        print(f"{args.source} manifest: {len(names)} tests, all accounted for")
        return 0

    if gone:
        print(f"\n{len(gone)} test(s) in the manifest no longer exist:", file=sys.stderr)
        for name in gone:
            print(f"  - {name}", file=sys.stderr)
        print(
            "\nIf that is deliberate, delete those lines from tests/test_manifest.txt in the\n"
            "same commit that removes the tests, so the removal is visible in one diff.\n"
            "\n"
            "Before you do: some tests in this suite are load-bearing in a way their names\n"
            "do not advertise -- a case that fails on purpose, an assertion that cannot\n"
            "fire, a guard whose passing output looks like no guard at all. See\n"
            "docs/PROTECTED.md.",
            file=sys.stderr,
        )

    if added:
        print(f"\n{len(added)} test(s) are not in the manifest:", file=sys.stderr)
        for name in added:
            print(f"  + {name}", file=sys.stderr)
        print(
            "\nRegenerate with:\n"
            f"  python scripts/check_test_manifest.py --source {args.source} ... --write\n"
            "\n"
            "New tests fail this check on purpose: recording them is what makes a guard\n"
            "written today protected tomorrow.",
            file=sys.stderr,
        )

    return 1


if __name__ == "__main__":
    raise SystemExit(main())
