"""Writes a generated panel out in the formats the C++ engine already reads.

Spec 2 M4 asks the generator to emit a synthetic membership history so the
universe machinery is exercised. This is that, plus the bars to go with it,
because a membership history with no prices behind it cannot be replayed.

Nothing here invents a format. The bars are the `date,symbol,open,high,low,
close,volume` CSV that `scripts/csv_to_msb.py` converts into the binary cache,
and the membership file is the `date,TICKER,TICKER,...` snapshot layout that
`SnapshotMembershipSource` parses -- the same shape as the free S&P history, so
the synthetic panel enters the engine through the identical path real data does
rather than through a test-only door.

    python -m research.export --out data/cache/synthetic --periods 500

Then, to put it in front of the engine:

    python scripts/csv_to_msb.py data/cache/synthetic/bars.csv --out data/cache/synthetic/bars
    marketscan.exe --headless --build-universe data/cache/synthetic/membership.csv
    marketscan.exe --headless --daily data/cache/synthetic/bars \
                   --universe data/cache/synthetic/membership.csv

WHAT THE BARS ARE NOT

The panel model has one return per period and no intraday process at all, so
`open`, `high` and `low` are synthesized around the close: the open is the
previous close and the range is a fixed fraction of the period's own return.
They exist because the format has columns for them. Nothing should ever measure
anything with them -- the engine synthesizes its quotes from the close and a
configured spread, which is why this is harmless. If something here ever starts
reading the high, that is the moment to replace this with an intraday process
rather than to trust it.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from research.panel import Panel, PanelSpec, generate_panel

REPO = Path(__file__).resolve().parent.parent

_RANGE_FRACTION = 0.3
"""How much of a period's return the synthesized high/low reach beyond it."""


def bars_frame(panel: Panel) -> pd.DataFrame:
    """The panel as daily OHLCV rows, one per (date, security) membership day."""
    close = panel.wide("price")
    volume = panel.wide("volume")
    returns = panel.wide("ret")

    # The open is the previous close where there is one. On a name's first day
    # there is not, so it is backed out of the return -- which makes the first
    # bar's open the price the name would have had the period before, not a
    # number pulled from nowhere.
    previous = close.shift(1)
    first_open = close / (1.0 + returns)
    open_ = previous.where(previous.notna() & close.notna(), first_open)

    span = (_RANGE_FRACTION * returns.abs()).fillna(0.0)
    high = np.maximum(open_, close) * (1.0 + span)
    low = np.minimum(open_, close) * (1.0 - span)

    def stack(wide: pd.DataFrame, name: str) -> pd.Series:
        stacked = wide.stack()
        stacked.index.names = ["date", "symbol"]
        return stacked.rename(name)

    frame = pd.concat(
        [stack(open_, "open"), stack(high, "high"), stack(low, "low"),
         stack(close, "close"), stack(volume, "volume")],
        axis=1,
    ).dropna()

    # Only membership days: the panel frame is the authority on which (date,
    # security) pairs exist, and a bar outside a membership period would be a
    # price for a company the universe says was not there.
    frame = frame.loc[frame.index.intersection(panel.frame.index)].sort_index()
    return frame.reset_index()


def membership_snapshots(panel: Panel) -> list[tuple[pd.Timestamp, list[str]]]:
    """One snapshot per date: the members on it, sorted.

    Sorted because the file is compared between runs and a set's order is not a
    property of the data.
    """
    members = panel.frame.index.to_frame(index=False).groupby("date")["security"]
    return [(date, sorted(group)) for date, group in members]


def write_bars(panel: Panel, path: Path) -> int:
    frame = bars_frame(panel)
    path.parent.mkdir(parents=True, exist_ok=True)
    frame = frame.assign(date=frame["date"].dt.strftime("%Y-%m-%d"))
    for column in ("open", "high", "low", "close"):
        frame[column] = frame[column].map(lambda v: f"{v:.4f}")
    frame["volume"] = frame["volume"].round().astype(np.int64)
    frame.to_csv(path, index=False, columns=["date", "symbol", "open", "high", "low", "close",
                                             "volume"])
    return len(frame)


def write_membership(panel: Panel, path: Path) -> int:
    snapshots = membership_snapshots(panel)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# Synthetic membership history generated by research/export.py.\n")
        out.write("# Not market data. See research/README.md.\n")
        out.write(f"# seed={panel.spec.seed} lam={panel.spec.lam:g} "
                  f"n_securities={panel.spec.n_securities} periods={panel.spec.n_periods}\n")
        for date, members in snapshots:
            out.write(f"{date.strftime('%Y-%m-%d')},{','.join(members)}\n")
    return len(snapshots)


def export_panel(panel: Panel, out_dir: Path) -> dict[str, object]:
    """Writes bars, membership and provenance. Returns what it wrote."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    bars = write_bars(panel, out_dir / "bars.csv")
    snapshots = write_membership(panel, out_dir / "membership.csv")

    # The spec, beside the data. A synthetic dataset whose parameters are not
    # recorded next to it becomes indistinguishable from real data the moment
    # somebody copies the directory, and that is a mistake worth engineering
    # against rather than remembering.
    provenance = {
        "generator": "research/panel.py",
        "spec": panel.spec.to_dict(),
        "bars": bars,
        "snapshots": snapshots,
        "securities": int(len(panel.securities)),
        "warning": "Synthetic data. Not market data. Every number derived from it is a "
                   "statement about the pipeline.",
    }
    (out_dir / "panel.json").write_text(json.dumps(provenance, indent=2, default=str),
                                        encoding="utf-8")
    return provenance


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=REPO / "data" / "cache" / "synthetic",
                        help="directory to write into (default: data/cache/synthetic, gitignored)")
    parser.add_argument("--securities", type=int, default=PanelSpec.n_securities)
    parser.add_argument("--periods", type=int, default=PanelSpec.n_periods)
    parser.add_argument("--lam", type=float, default=PanelSpec.lam)
    parser.add_argument("--seed", type=int, default=PanelSpec.seed)
    parser.add_argument("--delist-hazard", type=float, default=0.0004,
                        help="per-period departure probability; the default gives a membership "
                             "history that actually changes")
    parser.add_argument("--delist-tilt", type=float, default=0.5)
    args = parser.parse_args(argv)

    panel = generate_panel(PanelSpec(
        n_securities=args.securities,
        n_periods=args.periods,
        lam=args.lam,
        seed=args.seed,
        delist_hazard=args.delist_hazard,
        delist_exposure_tilt=args.delist_tilt,
    ))
    print(panel.describe())
    written = export_panel(panel, args.out)
    print(f"wrote {written['bars']} bars and {written['snapshots']} snapshots to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
